// Builds the one file the Claude Code plugin ships as its command, plugins/vienkartine/bin/vienkartine: the CLI and
// everything it imports (age-encryption and its dependencies) bundled, unminified so that it can be read, for Node.
// Run `bun run build:plugin` after any change to cli/ or src/shared/. test/plugin.test.ts fails while the shipped
// file differs from a fresh build.

import { chmodSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
export const SHIPPED = join(ROOT, "plugins/vienkartine/bin/vienkartine");

export async function buildPluginCli(): Promise<string> {
  // Bun writes file paths into the bundle's comments relative to the working directory, so build from the repository
  // root whatever the caller's directory is: the same sources then give the same bytes anywhere.
  const here = process.cwd();
  process.chdir(ROOT);
  let result: Awaited<ReturnType<typeof Bun.build>>;
  try {
    result = await Bun.build({
      entrypoints: ["cli/vienkartine.ts"],
      target: "node",
      format: "cjs", // an extensionless file runs as CommonJS on every Node version, with no module detection needed
      minify: false,
      sourcemap: "none",
    });
  } finally {
    process.chdir(here);
  }
  if (!result.success) throw new Error(`plugin build failed:\n${result.logs.join("\n")}`);
  // Bun carries over the CLI's own shebang (the Bun flags); the shipped file runs on Node.
  const code = (await result.outputs[0].text()).replace(/^#!.*\n/, "");
  return `#!/usr/bin/env node\n// Generated by scripts/build-plugin.ts from cli/vienkartine.ts. Do not edit: run \`bun run build:plugin\`.\n${code}`;
}

if (import.meta.main) {
  writeFileSync(SHIPPED, await buildPluginCli());
  chmodSync(SHIPPED, 0o755);
  console.log(`wrote ${SHIPPED}`);
}
