// Builds the two files the Claude Code plugin ships for its command: plugins/vienkartine/bin/vienkartine (the CLI and
// everything it imports, age-encryption and its dependencies, bundled and unminified so that it can be read, for Node)
// and plugins/vienkartine/THIRD_PARTY_NOTICES (the licence of every package that went into the bundle).
// Run `bun run build:plugin` after any change to cli/, src/shared/ or the version of a bundled dependency.
// test/plugin.test.ts fails while a shipped file differs from a fresh build.

import { chmodSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
export const SHIPPED = join(ROOT, "plugins/vienkartine/bin/vienkartine");
export const NOTICES = join(ROOT, "plugins/vienkartine/THIRD_PARTY_NOTICES");

/** The licence text of each package in `node_modules` that the build pulled in, one block per package and version. */
function thirdPartyNotices(inputs: string[]): string {
  // The nearest node_modules/<package> above each input file: the greedy match picks nested copies correctly.
  const roots = new Set<string>();
  for (const file of inputs) {
    const root = /^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//.exec(file)?.[1];
    if (root) roots.add(root);
  }
  const blocks = [...roots].sort().map((root) => {
    const { name, version, license } = JSON.parse(readFileSync(join(ROOT, root, "package.json"), "utf8")) as { name: string; version: string; license?: string };
    const file = readdirSync(join(ROOT, root)).find((entry) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(entry));
    if (!file) throw new Error(`no licence file in ${root}: add its notice by hand before shipping it`);
    return `${"=".repeat(78)}\n${name} ${version} (${license ?? "see below"})\n${"=".repeat(78)}\n\n${readFileSync(join(ROOT, root, file), "utf8").trim()}\n`;
  });
  return `Third-party software in plugins/vienkartine/bin/vienkartine

The command bundles the packages below. Their licences require the notices to be kept with copies of the software.
This file is generated by scripts/build-plugin.ts from each package's licence file: do not edit it, run \`bun run build:plugin\`.

${blocks.join("\n")}`;
}

export async function buildPlugin(): Promise<{ cli: string; notices: string }> {
  // Bun writes file paths into the bundle's comments relative to the working directory, so build from the repository
  // root whatever the caller's directory is: the same sources then give the same bytes anywhere.
  const here = process.cwd();
  process.chdir(ROOT);
  let result: Awaited<ReturnType<typeof Bun.build>>;
  try {
    result = await Bun.build({
      entrypoints: ["cli/vienkartine.ts"],
      target: "node",
      format: "cjs", // an extensionless file runs as CommonJS on every Node version, with no module detection needed
      minify: false,
      sourcemap: "none",
      metafile: true,
    });
  } finally {
    process.chdir(here);
  }
  if (!result.success) throw new Error(`plugin build failed:\n${result.logs.join("\n")}`);
  // Bun carries over the CLI's own shebang (the Bun flags); the shipped file runs on Node.
  const code = (await result.outputs[0].text()).replace(/^#!.*\n/, "");
  return {
    cli: `#!/usr/bin/env node\n// Generated by scripts/build-plugin.ts from cli/vienkartine.ts. Do not edit: run \`bun run build:plugin\`.\n${code}`,
    notices: thirdPartyNotices(Object.keys(result.metafile!.inputs)),
  };
}

if (import.meta.main) {
  const { cli, notices } = await buildPlugin();
  writeFileSync(SHIPPED, cli);
  chmodSync(SHIPPED, 0o755);
  writeFileSync(NOTICES, notices);
  console.log(`wrote ${SHIPPED} and ${NOTICES}`);
}
